type MockHistoryPeriod = '24h' | '7d' | '30d'

const historyConfig: Record<MockHistoryPeriod, { points: number; durationMs: number; trendScale: number }> = {
  '24h': { points: 25, durationMs: 24 * 60 * 60 * 1_000, trendScale: 1 },
  '7d': { points: 29, durationMs: 7 * 24 * 60 * 60 * 1_000, trendScale: 1.85 },
  '30d': { points: 31, durationMs: 30 * 24 * 60 * 60 * 1_000, trendScale: 3.2 },
}

function historySeed(symbol: string, period: MockHistoryPeriod): number {
  return [...`${symbol}:${period}`].reduce((seed, character) => (
    (seed * 31 + character.charCodeAt(0)) >>> 0
  ), 2166136261)
}

function deterministicNoise(seed: number, index: number): number {
  let value = (seed + Math.imul(index + 1, 0x6d2b79f5)) >>> 0
  value = Math.imul(value ^ (value >>> 15), value | 1)
  value ^= value + Math.imul(value ^ (value >>> 7), value | 61)
  return ((value ^ (value >>> 14)) >>> 0) / 4_294_967_296
}

function createPriceHistory(
  asset: MarketAsset,
  period: MockHistoryPeriod,
  assetIndex: number,
): PricePoint[] {
  const config = historyConfig[period]
  const base = Number(asset.sellPriceToman)
  const change = Number(asset.change24hPercent) / 100
  const seed = historySeed(asset.symbol, period)
  const volatility = 0.006 + assetIndex * 0.0015
  const endTime = Date.parse(MOCK_NOW)

  return Array.from({ length: config.points }, (_, index) => {
    const progress = index / (config.points - 1)
    const trend = -change * config.trendScale * (1 - progress)
    const wave = Math.sin(progress * Math.PI * (2.4 + assetIndex * .35) + assetIndex)
      * volatility * Math.sin(progress * Math.PI)
    const noise = (deterministicNoise(seed, index) - .5)
      * volatility * .75 * Math.sin(progress * Math.PI)
    const price = index === config.points - 1
      ? base
      : Math.max(1, Math.round(base * (1 + trend + wave + noise)))
    const timestamp = new Date(endTime - config.durationMs + (config.durationMs * progress)).toISOString()
    return { timestamp, priceToman: String(price) }
  })
}

